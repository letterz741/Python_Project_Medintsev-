#Дано трехзначное число, вывести число, полученное при перестановки чисел цифр сотен  и десятков исходного числа
while True:
     try:
         n = int(input("Введите трёхзначное число:"))
         if 100 <= n <= 999:
           break
           print("Ошибка: число должно быть трёхзначным (100-999).")
     except ValueError:
         print("Ошибка: нужно ввести целое число.")
a = n // 100
b = n // 10 % 10
c = n % 10
print(b * 100 + a * 10 + c)


